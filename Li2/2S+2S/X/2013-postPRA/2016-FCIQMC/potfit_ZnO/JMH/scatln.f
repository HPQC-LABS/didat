c***********************************************************************
      SUBROUTINE SCATLN(P,H,RMIN,V,N,E0,NCN,KV,ASCAT,VDFRAC,SCHR)
C
C  SOLVES THE SCHROEDINGER-TYPE EQUATION
C       D2(PSI)/DR2 + (E-V(R))*PSI =0
C  WITH THIS EQUATION DETERMINING THE UNITS
C  TO OBTAIN THE SCATTERING LENGTH
C
C  ROUTINE MODIFIED JULY 2002 BY JEREMY HUTSON FROM
C  AN ANCIENT SCHROEDINGER SOLVER BY RICHARD ZARE.
C  PARTS OF IT ARE SO OLD THEY HAVE COMPUTED GOTOS,
C  A FORTRAN CONSTRUCT DEPRECATED SINCE FORTRAN IV!
C
C  P:     WAVEFUNCTION AT ENERGY E0 (OUTPUT)
C  KV:    NUMBER OF NODES FOUND AT E0 
C         (1 + INTEGER PART OF VD) (OUTPUT)
C  H:     STEP SIZE
C  RMIN:  DISTANCE CORRESPONDING TO V(1) (INPUT)
C  V:     SCALED POTENTIAL WITH DIMENSIONS OF 1/LENGTH**2,
C         USUALLY 2*MU*V/HBAR**2
C  N:     NUMBER OF V POINTS (INPUT)
C  E0:    ENERGY AT THRESHOLD (USED FOR CALCULATION) (INPUT)
C  NCN:   LONGEST-RANGE POTENTIAL TERM IS -CN/R**NCN (INPUT) 
C  ASCAT: SCATTERING LENGTH (OUTPUT)
C  SCHR:  INTEGER ERROR INDICATOR (OUTPUT: ZERO FOR SUCCESS)
C
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INTEGER SCHR
C
      DIMENSION V(N),P(N)
      DATA ZERO/0.0D0/, ONE/1.0D0/
C
      H2=H**2
      HV=H**2/12.0D0
      E=E0
      PMIN=1.0D-30
      PMAX=1.0D30
C
C  .....TEST IF V TOO HIGH
C
      IF(V(N).GT.E) THEN
          WRITE(6,*) ' V > E AT OUTERMOST POINT'
          SCHR=2
          RETURN
          ENDIF
C
C  .....START OUTWARD INTEGRATION
C
      P1=PMIN
      P(1)=P1
      Y1=ZERO
      GI=V(1)-E
      Y2=(ONE-HV*GI)*P1
      M=N
      DO  I=2,M
          Y3=Y2+((Y2-Y1)+H2*GI*P1)
          GI=V(I)-E
          P1=Y3/(ONE-HV*GI)
          P(I)=P1
          Y1=Y2
          Y2=Y3
C
          IF(DABS(P(I)).GE.PMAX)  THEN
              PX=ONE/P1
              DO  J=1,I
                  IF(DABS(P(J)).LT.PMIN) THEN 
                      P(J)=ZERO
                    ELSE
                      P(J)=P(J)*PX
                    ENDIF
                  ENDDO
              Y1=Y1*PX
              Y2=Y2*PX
              P1=ONE
              ENDIF
          ENDDO
C
C  .....FINISHED OUTWARD INTEGRATION
C
      PM=ONE/P1
      YOUT=Y1/P1
      YM=Y2/P1
      DO  J=1,M
          IF(ABS(P(J)).LT.PMIN) THEN 
              P(J)=ZERO
            ELSE
              P(J)=P(J)*PM
            ENDIF
          ENDDO
C
C  .....CONVERGED-COUNT NODES
C  THIS IS NOT COMPLETELY RELIABLE BECAUSE THERE CAN BE
C  NODES BEYOND RMAX.
C
      SCHR=0
      KV=0
      DO  J=2,N
          IF(V(J).LE.E) THEN 
              PPP=SIGN(ONE,P(J))*SIGN(ONE,P(J-1))
              IF(PPP.LE.ZERO) KV=KV+1
              ENDIF
          ENDDO
C
C  PRIMITIVE SCATTERING LENGTH ASSUMING LINEARITY
C
      RNOW=RMIN+H*DBLE(N-2)
      ASCAT=RNOW-P(N-1)*(H+H)/(P(N)-P(N-2))
      VDFRAC=0.D0
C  WRITE(6,*) 'PRIMITIVE SCATTERING LENGTH =',ASCAT
C
C  MATCH TO BESSEL AND NEUMANN FUNCTIONS TO TAKE ACCOUNT OF
C  LONG-RANGE 1/R**NCN BEYOND RMAX
C  SEE E.G. EQ. (13) OF GRIBAKIN AND FLAMBAUM,
C  PHYS REV A 48, 546 (1993).
C
      IF(NCN.GT.0) THEN
C
C  GET CN COEFFICIENT FROM POTENTIAL AT LAST POINT
C
          RNOW=RMIN+H*DBLE(N-1)
          GAM=SQRT((E-V(N))*RNOW**NCN)
C
C  GET BESSEL FUNCTIONS AT LAST POINT
C
          BESORD=1.D0/DBLE(NCN-2)
          BESARG=2.D0*GAM*BESORD*RNOW**(-0.5D0/BESORD)
          CALL BESSJY(BESARG,BESORD,RJ1,RY1,RJP,RYP)
          RJ1=RJ1*SQRT(RNOW)
          RY1=RY1*SQRT(RNOW)
C
C  GET BESSEL FUNCTIONS AT LAST POINT BUT TWO
C
          RNOW=RMIN+H*DBLE(N-3)
          BESARG=2.D0*GAM*BESORD*RNOW**(-0.5D0/BESORD)
          CALL BESSJY(BESARG,BESORD,RJ2,RY2,RJP,RYP)
          RJ2=RJ2*SQRT(RNOW)
          RY2=RY2*SQRT(RNOW)
C
C  MATCH NUMERICAL SOLUTION TO AA * J - BB * Y
C
          AA=(RY2*P(N)-RY1*P(N-2))/(RJ1*RY2-RY1*RJ2)
          BB=(RJ2*P(N)-RJ1*P(N-2))/(RJ1*RY2-RY1*RJ2)
C
C  GET "MEAN" AND ACTUAL SCATTERING LENGTHS (G&F, EQ. (14))
C
          PI=ACOS(-1.D0)
          ABAR=COS(PI*BESORD)*(GAM*BESORD)**(2.D0*BESORD)
     1      *GAMMA(BESORD*DBLE(NCN-3))/GAMMA(BESORD*DBLE(NCN-1))
          TANPH=AA/BB
          ASCAT=ABAR*(1.D0-TANPH*TAN(PI*BESORD))
C
C  EXPRESS THIS IN TERMS OF THE FRACTIONAL PART OF THE
C  QUANTUM NUMBER AT DISSOCIATION
C
        VDFRAC= DATAN2(AA,BB)/PI+0.5D0
C  WRITE(6,*) 'RAW vD = ',KV,' + vD(frac) = ',VDFRAC
C  WRITE(6,*) 'WHERE tan(vD(frac) - 0.5) = ',tanph,' = ',
C    1      aa,' / ',bb
        IF(VDFRAC.GT.1.D0) THEN
C  THIS INDICATES THAT THERE IS A NODE BEYOND RMAX
          VDFRAC=VDFRAC-1.D0
          KV=KV+1
        ELSEIF(VDFRAC.LT.0.D0) THEN
          WRITE(6,*) 'WARNING IN SCATLN: UNRELIABLE NODE COUNT.'
          WRITE(6,*) 'INCREASE RMAX TO ENSURE THAT NODES ARE ',
     1      'COUNTED CORRECTLY'
          VDFRAC=VDFRAC+1.D0
          KV=KV+1
        ENDIF
      ENDIF
C
      RETURN
      END
c=======================================================================
      DOUBLE PRECISION FUNCTION GAMMA(X)
      DOUBLE PRECISION S14AAF
      IFAIL=0
      GAMMA=S14AAF(X,IFAIL)
      RETURN
      END
